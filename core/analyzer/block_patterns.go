package analyzer

import (
	"strings"

	"pad-core/models"
)

// terminatorNames are the block names / raw types that indicate a flow
// termination point (exit subflow, end flow, return, etc.).
// These are vendor-specific strings emitted by Power Automate when exporting
// flows — they cannot be a typed enum because the parser maps them to
// BlockTypeAction with these raw names rather than a distinct BlockType.
var terminatorNames = []string{
	"ExitSubflow",
	"Exit subflow",
	"End flow",
	"EndFlow",
	"Return",
	"TerminateFlow",
	// PAD's own EXIT statement, which is how a real exported flow terminates —
	// and which was missing. `EXIT` / `EXIT FUNCTION` parse to RawType "EXIT"
	// (Name "EXIT" or "EXIT FUNCTION"), and none of the names above matched
	// either, so `dead-code` never fired on genuinely unreachable code after a
	// real exit. It fired on comments instead (see matchesAny). Note "EXIT" is a
	// RawType TOKEN match, so "EXIT_LOOP" is deliberately excluded: leaving a
	// loop is not leaving the flow.
	"EXIT",
	"EXIT FUNCTION",
}

// exitLoopNames are the block names / raw types that indicate an early loop exit.
// Centralized here to avoid duplication between engine.go and rule_infinite_loop.go.
var exitLoopNames = []string{
	"ExitLoop",
	"Exit loop",
	"Break",
	"Return",
	"End flow",
	"ExitSubflow",
	"Exit subflow",
}

// matchesAny reports whether b is one of the named vendor constructs.
//
// The matching is deliberately asymmetric, and the asymmetry is the point:
//
//   - RawType is machine-generated by the PAD exporter ("ExitSubflow.Exit"), so a
//     TOKEN-prefix match is right — the pattern must be followed by end-of-string
//     or a separator, so "Return" matches "Return" and "Return.Value" but not
//     "ReturnedItems".
//   - Name is often HUMAN PROSE. For a COMMENT block the parser stores the
//     comment text itself in Name, so a substring match there read an ordinary
//     comment as a control-flow construct: "Returns the next transaction item"
//     contains "Return". Name therefore requires an exact (trimmed,
//     case-insensitive) match.
//
// That single substring match was the most damaging defect in the analyzer.
// isTerminator fed `dead-code`, whose auto-fix is `remove-block`, so a subflow
// whose leading comment happened to say "Returns …" had its entire body reported
// unreachable and then DELETED by `bakicli fix`. The mirror image was just as
// bad: isExitLoop meant a comment saying "Break out when the queue drains"
// satisfied hasExitCondition and hid a genuinely unbounded loop.
//
// COMMENT blocks are excluded outright — a comment cannot terminate a flow or
// exit a loop, whatever its text says.
func matchesAny(b *models.Block, patterns []string) bool {
	if b.Type == models.BlockTypeComment {
		return false
	}
	name := strings.TrimSpace(b.Name)
	for _, p := range patterns {
		if strings.EqualFold(name, p) || matchesRawTypeToken(b.RawType, p) {
			return true
		}
	}
	return false
}

// matchesRawTypeToken reports whether rawType is p, or begins with p followed by
// a separator — so a dotted vendor name like "ExitSubflow.Exit" matches
// "ExitSubflow" while "Returned" does not match "Return".
func matchesRawTypeToken(rawType, p string) bool {
	if len(rawType) < len(p) || !strings.EqualFold(rawType[:len(p)], p) {
		return false
	}
	if len(rawType) == len(p) {
		return true
	}
	next := rawType[len(p)]
	return !isRawTypeWordByte(next)
}

func isRawTypeWordByte(c byte) bool {
	return c == '_' ||
		(c >= 'a' && c <= 'z') ||
		(c >= 'A' && c <= 'Z') ||
		(c >= '0' && c <= '9')
}

// isExitLoop reports whether b would cause early exit from a loop.
func isExitLoop(b *models.Block) bool {
	return matchesAny(b, exitLoopNames)
}

// outputVar returns the variable a block writes: the _output property, or the
// _var property as a fallback. Returns "" when the block writes no variable.
// Centralizes the _output→_var fallback that was duplicated across rules.
func outputVar(b *models.Block) string {
	if b.Properties == nil {
		return ""
	}
	if v := b.Properties["_output"]; v != "" {
		return v
	}
	return b.Properties["_var"]
}

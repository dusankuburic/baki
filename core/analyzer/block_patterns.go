package analyzer

import (
	"strings"

	"pad-core/models"
)

// terminatorNames are the block names/raw types indicating flow termination —
// vendor-specific strings emitted by Power Automate on export; the parser maps
// them to BlockTypeAction, not a distinct BlockType.
var terminatorNames = []string{
	"ExitSubflow",
	"Exit subflow",
	"End flow",
	"EndFlow",
	"Return",
	"TerminateFlow",
	// PAD's own EXIT. "EXIT" is a RawType TOKEN match, so "EXIT_LOOP" is
	// deliberately excluded (leaving a loop is not leaving the flow); its
	// absence meant dead-code never fired after a real exit.
	"EXIT",
	"EXIT FUNCTION",
}

// exitLoopNames are the block names / raw types that indicate an early loop exit.
// Centralized here to avoid duplication between engine.go and rule_infinite_loop.go.
var exitLoopNames = []string{
	"ExitLoop",
	"Exit loop",
	"Break",
	"Return",
	"End flow",
	"ExitSubflow",
	"Exit subflow",
}

// matchesAny reports whether b is one of the named vendor constructs.
//
// Deliberately asymmetric, and the asymmetry is the point: RawType is
// machine-generated by the PAD exporter ("ExitSubflow.Exit"), so a
// TOKEN-prefix match is right; Name is often HUMAN PROSE (a COMMENT block's
// Name holds the comment text), so Name requires an exact (trimmed,
// case-insensitive) match. The old substring match read "Returns the next
// transaction item" as a terminator — isTerminator feeds dead-code whose
// auto-fix is remove-block, so `bakicli fix` deleted a subflow body — and
// "Break out when the queue drains" hid a genuinely unbounded loop. COMMENT
// blocks are excluded outright.
func matchesAny(b *models.Block, patterns []string) bool {
	if b.Type == models.BlockTypeComment {
		return false
	}
	name := strings.TrimSpace(b.Name)
	for _, p := range patterns {
		if strings.EqualFold(name, p) || matchesRawTypeToken(b.RawType, p) {
			return true
		}
	}
	return false
}

// matchesRawTypeToken reports whether rawType is p, or begins with p followed
// by a separator — "ExitSubflow.Exit" matches "ExitSubflow", "Returned" does
// not match "Return".
func matchesRawTypeToken(rawType, p string) bool {
	if len(rawType) < len(p) || !strings.EqualFold(rawType[:len(p)], p) {
		return false
	}
	if len(rawType) == len(p) {
		return true
	}
	next := rawType[len(p)]
	return !isRawTypeWordByte(next)
}

func isRawTypeWordByte(c byte) bool {
	return c == '_' ||
		(c >= 'a' && c <= 'z') ||
		(c >= 'A' && c <= 'Z') ||
		(c >= '0' && c <= '9')
}

func isExitLoop(b *models.Block) bool {
	return matchesAny(b, exitLoopNames)
}

// outputVar returns the variable a block writes — the _output property, or
// _var as a fallback; "" when the block writes no variable.
func outputVar(b *models.Block) string {
	if b.Properties == nil {
		return ""
	}
	if v := b.Properties["_output"]; v != "" {
		return v
	}
	return b.Properties["_var"]
}
